  function b64Bytes(text) {
    var clean = String(text || '').replace(/\s+/g, '');
    if (!clean) return null;
    if (!/^[A-Za-z0-9+/]+={0,2}$/.test(clean)) return null;
    var bin;
    try { bin = atob(clean); } catch (err) { return null; }
    var bytes = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i) & 0xff;
    return bytes;
  }

  function bytesToB64(bytes) {
    var bin = '';
    for (var i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
    return btoa(bin);
  }

  /* The 12-byte header of a DER SubjectPublicKeyInfo wrapping an Ed25519 key:
     SEQUENCE(0x2a) SEQUENCE(5) OID 1.3.101.112 BIT STRING(0x21) 0-unused-bits.
     "openssl pkey -pubout" hands you exactly this, 44 bytes, and RFC 8463 §3
     wants the 32 raw bytes from the end of it in p= instead. Recognising it by
     name is the difference between "the base64 is truncated" — which it is not,
     it is complete and correct, just wrapped — and "strip the wrapper, and here
     is the value you actually need". The first version offered only the two
     wrong explanations. */
  var ED25519_SPKI = [0x30, 0x2a, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x03, 0x21, 0x00];

  function ed25519RawFromSpki(bytes) {
    if (bytes.length !== 44) return null;
    for (var i = 0; i < ED25519_SPKI.length; i++) {
      if (bytes[i] !== ED25519_SPKI[i]) return null;
    }
    return bytes.subarray(12);
  }

  /* DER length octets: short form below 0x80, otherwise the low seven bits say
     how many octets carry the length. Everything is bounds-checked because the
     input is a base64 blob pasted from somewhere, which is to say hostile. */
  function derLength(bytes, at) {
    if (at >= bytes.length) return null;
    var first = bytes[at];
    if (first < 0x80) return { len: first, next: at + 1 };
    var n = first & 0x7f;
    if (!n || n > 4 || at + 1 + n > bytes.length) return null;
    var len = 0;
    for (var i = 0; i < n; i++) len = len * 256 + bytes[at + 1 + i];
    return { len: len, next: at + 1 + n };
  }

  /* Walk a SubjectPublicKeyInfo far enough to read the RSA modulus and say how
     many bits it is. Returns null on anything it does not recognise rather
     than guessing — a wrong key size printed confidently is worse than none. */
  function rsaModulusBits(bytes) {
    var at = 0, l;
    if (bytes[at] !== 0x30) return null;
    l = derLength(bytes, at + 1); if (!l) return null;
    at = l.next;
    if (bytes[at] !== 0x30) return null;
    l = derLength(bytes, at + 1); if (!l) return null;
    at = l.next + l.len;
    if (at >= bytes.length || bytes[at] !== 0x03) return null;
    l = derLength(bytes, at + 1); if (!l) return null;
    at = l.next;
    if (bytes[at] !== 0x00) return null;
    at += 1;
    if (bytes[at] !== 0x30) return null;
    l = derLength(bytes, at + 1); if (!l) return null;
    at = l.next;
    if (bytes[at] !== 0x02) return null;
    l = derLength(bytes, at + 1); if (!l) return null;
    var start = l.next, len = l.len;
    if (len < 1 || start + len > bytes.length) return null;
    while (len > 1 && bytes[start] === 0x00) { start++; len--; }
    var top = bytes[start], bits = (len - 1) * 8;
    while (top) { bits++; top = top >> 1; }
    return bits;
  }

  function buildDkim() {
    out.clear();
    var selector = val('dkim-selector');
    var domain = cleanDomain(val('dkim-domain'));
    var k = val('dkim-k');
    var p = String((byId('dkim-p') || {}).value || '').replace(/\s+/g, '');
    var testing = byId('dkim-test') && byId('dkim-test').checked;

    out.heading('DKIM — the public half of the signing key, in DNS');
    out.rule();

    var domProblem = domainProblem(domain);
    if (domProblem) {
      out.err('The domain ' + domProblem + '.');
      setCopy('');
      setStatus('domain not usable', 'is-err');
      return;
    }
    if (!selector) {
      out.err('No selector. A selector is the label that picks WHICH key, and');
      out.err('without one there is nowhere to publish this.');
      setCopy('');
      setStatus('selector missing', 'is-err');
      return;
    }
    if (!/^[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]*[A-Za-z0-9])?)*$/.test(selector)) {
      out.err('That selector has a character DKIM does not allow. RFC 6376 §3.1');
      out.err('makes a selector one or more dot-separated labels of letters,');
      out.err('digits and hyphens — no underscores, no spaces.');
      setCopy('');
      setStatus('selector not valid', 'is-err');
      return;
    }

    var owner = selector + '._domainkey.' + domain;
    out.row('published at', owner);
    out.row('key type', k);

    var tags = ['v=DKIM1', 'k=' + k];
    if (k === 'rsa') tags.push('h=sha256');
    if (testing) tags.push('t=y');
    tags.push('p=' + p);
    var record = tags.join('; ');

    out.line('');
    if (!p) {
      out.warn('No public key pasted, so the p= tag is empty.');
      out.warn('An empty p= is not a placeholder — it is the documented way to');
      out.warn('REVOKE a key. Publishing this record as it stands tells receivers');
      out.warn('that any signature using this selector must be treated as invalid.');
      out.line('');
    }

    out.line(record);
    out.line('');
    out.row('record length', record.length + ' characters');

    var keyOk = true;
    if (p) {
      var bytes = b64Bytes(p);
      if (!bytes) {
        keyOk = false;
        out.err('That p= value is not valid base64. Copy the key body only: no');
        out.err('BEGIN/END lines, no line breaks left in, no quotes.');
      } else {
        out.row('key material', bytes.length + ' bytes decoded');
        if (k === 'ed25519') {
          var raw = ed25519RawFromSpki(bytes);
          if (bytes.length === 32) {
            out.ok('32 bytes, which is the right size for an Ed25519 public key.');
          } else if (raw) {
            keyOk = false;
            out.warn('This is the DER-wrapped form: 44 bytes of SubjectPublicKeyInfo,');
            out.warn('which is what "openssl pkey -pubout" hands you. Nothing is wrong');
            out.warn('with the key — RFC 8463 §3 just wants the 32 raw bytes from inside');
            out.warn('the wrapper in p=, not the wrapper.');
            out.line('');
            out.line('  The 32 bytes it contains, base64:', 't-info');
            out.line('  ' + bytesToB64(raw), 't-info');
          } else {
            keyOk = false;
            out.warn('An Ed25519 public key is 32 raw bytes, and its DER-wrapped form is');
            out.warn('44. This decodes to ' + bytes.length + ', which is neither — so either it is');
            out.warn('an RSA key with k=ed25519 set by mistake, or the base64 is');
            out.warn('truncated.');
          }
          out.dim('Ed25519 signing is defined in RFC 8463 and is small and fast, but');
          out.dim('verifier support is still thinner than RSA. Publishing both — one');
          out.dim('selector each — is the usual way round that.');
        } else {
          var bits = rsaModulusBits(bytes);
          if (bits === null) {
            out.warn('This decoded, but it is not a DER SubjectPublicKeyInfo that this');
            out.warn('reader understands, so I cannot tell you the key size. That does');
            out.warn('not necessarily mean it is wrong — only that I will not guess.');
          } else {
            out.row('RSA modulus', bits + ' bits');
            if (bits < 1024) {
              out.err('Under 1024 bits. RFC 8301 sets 1024 as the floor for verifiers,');
              out.err('so a key this small may be rejected outright.');
            } else if (bits < 2048) {
              out.warn(bits + '-bit works everywhere but is the old default. RFC 8301');
              out.warn('says signers SHOULD use 2048. Worth taking care of during the');
              out.warn('next rotation rather than as an emergency.');
            } else {
              out.ok(bits + '-bit RSA — at or above what RFC 8301 asks signers for.');
            }
            if (bits > 2048) {
              out.dim('Above 2048 the record gets long, and some DNS providers and some');
              out.dim('verifiers handle very long TXT records badly. 2048 is the size');
              out.dim('almost everyone settles on.');
            }
          }
        }
      }
    }

    /* A DKIM record with a broken p= is worse than no record at all: the
       selector exists, so every message signed with it fails verification
       instead of going unsigned. That is why this one refuses to hand the
       record over, the same way the SPF tab refuses an over-length record —
       the earlier version printed "not valid base64" and then offered the
       record for copying four lines further down. */
    out.rule();
    if (keyOk) {
      out.heading('Publish it as');
    } else {
      out.heading('Not offered for publishing');
      out.warn('The p= value above is not one a verifier will accept, and a record');
      out.warn('with a broken p= is worse than none: the selector exists, so every');
      out.warn('message signed with it fails rather than going unsigned. Shown here');
      out.warn('so you can see what you have; Copy record is switched off.');
      out.line('');
    }
    if (record.length > 255) {
      out.line('  ' + owner + '.  IN  TXT', keyOk ? null : 't-dim');
      out.line('      ' + quoteChunks(record), keyOk ? null : 't-dim');
      out.line('');
      out.warn('This record is ' + record.length + ' characters. A single TXT');
      out.warn('character-string stops at 255, so it must go out as the several');
      out.warn('quoted strings above, which the resolver joins back together.');
      out.warn('This is the single most common reason a freshly published 2048-bit');
      out.warn('DKIM key does not verify: the panel silently truncated it.');
    } else {
      out.line('  ' + owner + '.  IN  TXT  ' + quoteChunks(record), keyOk ? null : 't-dim');
    }

    out.rule();
    out.heading('What a selector is for');
    out.dim('The selector is an arbitrary label you choose. It exists so a domain');
    out.dim('can have more than one key at once: the signature on a message carries');
    out.dim('s=' + selector + ' and d=' + domain + ', and the verifier looks up exactly');
    out.dim('that one name. Nothing enumerates selectors, which is also why a');
    out.dim('scanner cannot list your keys — it can only guess common names.');
    out.line('');
    out.heading('Rotating without breaking anything');
    out.dim('1. Publish the NEW selector alongside the old one. Both records live.');
    out.dim('2. Leave it a while, so every resolver that cached the zone has seen it.');
    out.dim('3. Switch the signer to the new selector.');
    out.dim('4. Leave the OLD record published. Mail signed before the switch is');
    out.dim('   still in transit, still being retried, still sitting in a queue');
    out.dim('   somewhere — and it verifies against the old key or not at all.');
    out.dim('5. Only then remove the old record.');
    out.line('');
    out.dim('Deleting the old key at step 3 is the classic rotation outage. There is');
    out.dim('no fixed number of days for step 4; long enough to cover your longest');
    out.dim('retry window, and people commonly leave it a week or more.');

    out.rule();
    out.heading('This page will not generate a key');
    out.dim('Not as an omission — as a refusal. A private key generated by a web');
    out.dim('page is a key that page has seen, and there is no way for you to');
    out.dim('verify from the outside that it was not kept, logged or derived from a');
    out.dim('predictable seed. You would be taking my word for it, and you should');
    out.dim('not have to.');
    out.line('');
    out.dim('Generate it where you control the machine. Your mail provider will');
    out.dim('usually do it for you and hand you the public half, which is better');
    out.dim('still, because then the private half never travels at all.');

    if (!keyOk) {
      setCopy('');
      setStatus('key not usable — record not offered', 'is-err');
      return;
    }
    setCopy(record);
    out.line('');
    out.dim('Copy record puts the TXT value on your clipboard, without the quotes.');
    setStatus('built ' + owner, 'is-ok');
  }

  /* ==================================================================
     4. DMARC aggregate (RUA) report parser
     ================================================================== */

  function textOf(node, tag) {
    if (!node) return '';
    var found = node.getElementsByTagName(tag);
    if (!found || !found.length) return '';
    return String(found[0].textContent || '').trim();
  }

  function firstOf(node, tag) {
    if (!node) return null;
    var found = node.getElementsByTagName(tag);
    return found && found.length ? found[0] : null;
  }

  function epochLabel(text) {
    var n = parseInt(text, 10);
    if (!isFinite(n) || n <= 0) return '(not stated)';
    var d = new Date(n * 1000);
    if (isNaN(d.getTime())) return '(unreadable: ' + text + ')';
    return d.toISOString().replace('T', ' ').replace(/\.\d+Z$/, ' UTC');
  }

  function classify(spfAligned, dkimAligned) {
    if (dkimAligned === 'pass' && spfAligned === 'pass') return 'your own, both aligned';
    if (dkimAligned === 'pass' && spfAligned !== 'pass') return 'forwarded or relayed — DKIM carried it';
    if (dkimAligned !== 'pass' && spfAligned === 'pass') return 'SPF only — breaks when forwarded';
    return 'fails DMARC — reject would stop this';
  }

  function parseReport() {
    out.clear();
    var xml = String((byId('rua-xml') || {}).value || '').trim();
    if (!xml) {
      out.warn('Paste the XML from inside the aggregate report first.');
      out.line('');
      out.dim('Aggregate reports arrive as a .gz or .zip attachment. This tool does');
      out.dim('not decompress either one — unzip it yourself and paste the XML.');
      out.dim('That is a deliberate limit, not an oversight: the parsing is the hard');
      out.dim('part and the decompression is one command you already have.');
      setCopy('');
      setStatus('nothing pasted', 'is-err');
      return;
    }

    var doc = new DOMParser().parseFromString(xml, 'text/xml');
    var bad = doc.getElementsByTagName('parsererror');
    if (bad && bad.length) {
      out.err('That is not well-formed XML.');
      out.line('');
      out.dim('The parser said:');
      String(bad[0].textContent || 'no detail given').split('\n').forEach(function (line) {
        if (line.trim()) out.dim('  ' + line.trim());
      });
      out.line('');
      out.dim('The usual causes: the .gz was pasted rather than its contents, the');
      out.dim('paste was truncated, or a mail client wrapped the lines and broke a');
      out.dim('tag across two of them.');
      setCopy('');
      setStatus('XML did not parse', 'is-err');
      return;
    }

    var root = doc.documentElement;
    if (!root || root.nodeName !== 'feedback') {
      out.warn('The root element is "' + (root ? root.nodeName : 'missing') +
        '", not "feedback".');
      out.warn('This may not be a DMARC aggregate report. Reading it anyway.');
      out.line('');
    }

    var meta = firstOf(root, 'report_metadata');
    var range = meta ? firstOf(meta, 'date_range') : null;
    out.heading('Report metadata');
    out.row('from', textOf(meta, 'org_name') || '(not stated)');
    out.row('contact', textOf(meta, 'email') || '(not stated)');
    out.row('report id', textOf(meta, 'report_id') || '(not stated)');
    out.row('covers from', epochLabel(textOf(range, 'begin')));
    out.row('covers to', epochLabel(textOf(range, 'end')));

    var pol = firstOf(root, 'policy_published');
    out.rule();
    out.heading('Policy this receiver saw');
    out.row('domain', textOf(pol, 'domain') || '(not stated)');
    out.row('p', textOf(pol, 'p') || '(not stated)');
    if (textOf(pol, 'sp')) out.row('sp', textOf(pol, 'sp'));
    out.row('adkim', (textOf(pol, 'adkim') || 'r') + ' (' +
      (textOf(pol, 'adkim') === 's' ? 'strict' : 'relaxed') + ')');
    out.row('aspf', (textOf(pol, 'aspf') || 'r') + ' (' +
      (textOf(pol, 'aspf') === 's' ? 'strict' : 'relaxed') + ')');
    if (textOf(pol, 'pct')) out.row('pct', textOf(pol, 'pct'));

    var recs = root.getElementsByTagName('record');
    if (!recs.length) {
      out.rule();
      out.warn('No <record> elements. The report is structurally fine and says');
      out.warn('this receiver saw no mail claiming to be from the domain in the');
      out.warn('period covered. Empty reports are normal for a quiet domain.');
      setCopy('');
      setStatus('parsed — no records', 'is-ok');
      return;
    }

    var sources = {};
    var order = [];
    var total = 0, passed = 0, wouldReject = 0;
    var dispositions = {};
    var unalignedSigners = {};

    /* A <count> is the messages one source IP sent to one receiver over one
       period, so a billion is already past anything real. Without a ceiling,
       parseInt happily returns 1e21 from a corrupt or hostile report and every
       total below it prints as "1e+21 messages" — arithmetic that has silently
       left the integers behind. Clamp, count how often, and say so. */
    var MAX_COUNT = 1000000000;
    var clamped = 0;

    for (var i = 0; i < recs.length; i++) {
      var rec = recs[i];
      var row = firstOf(rec, 'row');
      var pe = row ? firstOf(row, 'policy_evaluated') : null;
      var ident = firstOf(rec, 'identifiers');
      var auth = firstOf(rec, 'auth_results');

      var ip = textOf(row, 'source_ip') || textOf(row, 'source_ipv6') || '(no source_ip)';
      var count = parseInt(textOf(row, 'count'), 10);
      if (!isFinite(count) || count < 0) count = 0;
      if (count > MAX_COUNT) { count = MAX_COUNT; clamped++; }
      var disp = (textOf(pe, 'disposition') || 'none').toLowerCase();
      var dkimAligned = (textOf(pe, 'dkim') || 'fail').toLowerCase();
      var spfAligned = (textOf(pe, 'spf') || 'fail').toLowerCase();
      var headerFrom = (textOf(ident, 'header_from') || '').toLowerCase();

      total += count;
      dispositions[disp] = (dispositions[disp] || 0) + count;
      var dmarcPass = dkimAligned === 'pass' || spfAligned === 'pass';
      if (dmarcPass) passed += count;
      else wouldReject += count;

      if (!sources[ip]) {
        sources[ip] = {
          ip: ip, count: 0, dkim: dkimAligned, spf: spfAligned,
          disp: {}, from: {}, signers: {}, spfDomains: {}
        };
        order.push(ip);
      }
      var s = sources[ip];
      s.count += count;
      s.disp[disp] = true;
      if (headerFrom) s.from[headerFrom] = true;
      /* One source IP can appear in several records with different results.
         Keeping the worst of each means a source that fails intermittently is
         not hidden behind the record that happened to pass. */
      if (dkimAligned !== 'pass') s.dkim = dkimAligned;
      if (spfAligned !== 'pass') s.spf = spfAligned;

      if (auth) {
        var dk = auth.getElementsByTagName('dkim');
        for (var j = 0; j < dk.length; j++) {
          var dd = (textOf(dk[j], 'domain') || '').toLowerCase();
          var dr = (textOf(dk[j], 'result') || '').toLowerCase();
          var ds = textOf(dk[j], 'selector');
          if (dd) s.signers[dd + (ds ? ' (s=' + ds + ')' : '') + ' ' + dr] = true;
          if (dr === 'pass' && dd && headerFrom && dd !== headerFrom &&
              dd.slice(-(headerFrom.length + 1)) !== '.' + headerFrom) {
            unalignedSigners[dd] = (unalignedSigners[dd] || 0) + count;
          }
        }
        var sp = auth.getElementsByTagName('spf');
        for (var m = 0; m < sp.length; m++) {
          var sd = (textOf(sp[m], 'domain') || '').toLowerCase();
          var sr = (textOf(sp[m], 'result') || '').toLowerCase();
          if (sd) s.spfDomains[sd + ' ' + sr] = true;
        }
      }
    }

    var list = order.map(function (ip) { return sources[ip]; });
    list.sort(function (a, b) { return b.count - a.count; });

    out.rule();
    out.heading('Totals');
    out.row('records in report', String(recs.length));
    out.row('distinct source IPs', String(list.length));
    out.row('messages', String(total));
    var rate = total ? (passed * 100 / total) : 0;
    out.row('DMARC pass', passed + ' of ' + total + ' (' + rate.toFixed(1) + '%)',
      rate >= 99 ? 't-ok' : (rate >= 90 ? 't-warn' : 't-err'));
    out.row('would fail at reject', wouldReject + ' (' +
      (total ? (wouldReject * 100 / total).toFixed(1) : '0.0') + '%)',
      wouldReject ? 't-warn' : 't-ok');
    Object.keys(dispositions).forEach(function (d) {
      out.row('disposition ' + d, String(dispositions[d]));
    });
    out.line('');
    if (clamped) {
      out.warn(clamped + (clamped === 1 ? ' record claimed a message count' : ' records claimed message counts') +
        ' above ' + MAX_COUNT + ', which is not a');
      out.warn('number a real report produces. Each was capped at that figure, so');
      out.warn('every total here is a floor rather than a count. Treat this file as');
      out.warn('corrupt or fabricated rather than as traffic.');
      out.line('');
    }
    out.dim('A message passes DMARC on EITHER aligned DKIM or aligned SPF. It does');
    out.dim('not need both, and the pass rate above is counted that way.');

    out.rule();
    out.heading('By source IP, largest first');
    out.line('  ' + pad('source', 24) + pad('msgs', 8) + pad('share', 8) +
      pad('DKIM', 7) + pad('SPF', 7) + 'what it looks like', 't-dim');
    list.forEach(function (s) {
      var share = total ? (s.count * 100 / total).toFixed(1) + '%' : '-';
      var verdict = classify(s.spf, s.dkim);
      var cls = 't-ok';
      if (s.dkim !== 'pass' && s.spf !== 'pass') cls = 't-err';
      else if (s.dkim !== 'pass' || s.spf !== 'pass') cls = 't-warn';
      out.line('  ' + pad(s.ip, 24) + pad(s.count, 8) + pad(share, 8) +
        pad(s.dkim, 7) + pad(s.spf, 7) + verdict, cls);
    });
    out.line('');
    out.dim('DKIM and SPF above are the ALIGNED results DMARC evaluated, not the');
    out.dim('raw check results. A source can pass SPF for its own domain and still');
    out.dim('read "fail" here, because it did not pass for the From: domain.');

    var forwarders = list.filter(function (s) {
      return s.dkim === 'pass' && s.spf !== 'pass';
    });
    out.rule();
    out.heading('The row everybody misreads');
    if (forwarders.length) {
      var fwd = 0;
      forwarders.forEach(function (s) { fwd += s.count; });
      out.warn(forwarders.length === 1
        ? '1 source here shows SPF fail with DKIM pass, covering ' + fwd + ' messages.'
        : forwarders.length + ' sources here show SPF fail with DKIM pass, covering ' +
          fwd + ' messages.');
      forwarders.forEach(function (s) { out.line('  ' + s.ip + '  (' + s.count + ')', 't-warn'); });
      out.line('');
      out.dim('That is the signature of forwarding, not spoofing. A mailing list or a');
      out.dim('user’s "send everything to my other address" rule re-sends your message');
      out.dim('from its own IP, which is not in your SPF, so SPF fails. The DKIM');
      out.dim('signature travels inside the message and still verifies, so DMARC');
      out.dim('passes on DKIM alone. Nothing is wrong. Do not chase these, and do not');
      out.dim('add the forwarder to your SPF — you cannot list every forwarder your');
      out.dim('recipients use, which is precisely why DKIM exists.');
    } else {
      out.ok('No source in this report shows the forwarding pattern (SPF fail with');
      out.ok('DKIM pass). If one appears later, it is almost certainly a forwarder');
      out.ok('rather than a spoofer.');
    }

    var spfOnly = list.filter(function (s) { return s.spf === 'pass' && s.dkim !== 'pass'; });
    if (spfOnly.length) {
      out.rule();
      out.heading('Passing on SPF alone');
      spfOnly.forEach(function (s) { out.line('  ' + s.ip + '  (' + s.count + ')', 't-warn'); });
      out.dim('These pass today and fail the moment a recipient forwards them, or');
      out.dim('the moment they reach a mailing list. Get an aligned DKIM signature');
      out.dim('on this sender before you move past p=none.');
    }

    var failing = list.filter(function (s) { return s.spf !== 'pass' && s.dkim !== 'pass'; });
    if (failing.length) {
      out.rule();
      out.heading('Failing both — this is what reject would stop');
      failing.forEach(function (s) {
        var froms = Object.keys(s.from);
        out.line('  ' + pad(s.ip, 24) + pad(s.count, 8) +
          (froms.length ? 'From: ' + froms.join(', ') : ''), 't-err');
        var signers = Object.keys(s.signers);
        if (signers.length) out.dim('      DKIM results seen: ' + signers.join('; '));
        var spfd = Object.keys(s.spfDomains);
        if (spfd.length) out.dim('      SPF results seen:  ' + spfd.join('; '));
      });
      out.line('');
      out.dim('Some of these are spoofers and some are a sender you forgot about.');
      out.dim('The volume usually tells you which: a handful of messages from many');
      out.dim('IPs is background spoofing, and a steady daily count from one IP is');
      out.dim('a service somebody in your organisation set up.');
    }

    var unaligned = Object.keys(unalignedSigners);
    if (unaligned.length) {
      out.rule();
      out.heading('Signatures that verified but did not align');
      unaligned.forEach(function (d) {
        out.line('  ' + pad(d, 32) + unalignedSigners[d] + ' messages', 't-warn');
      });
      out.dim('The signature is valid — the key is right and the message was not');
      out.dim('altered — but the d= domain is not the From: domain, so DMARC does');
      out.dim('not count it. This is what a third-party sender signing with its own');
      out.dim('domain looks like. Fix it by having them sign with a selector under');
      out.dim('your domain, which is a supported option at every serious vendor.');
      out.line('');
      out.dim('This one is a heuristic too: it calls a signature aligned when d= is');
      out.dim('the From: domain or a subdomain of it. Relaxed alignment is really');
      out.dim('about the organisational domain, so a d= one level ABOVE the From:');
      out.dim('domain aligns in practice and is listed here anyway. Working out the');
      out.dim('organisational domain needs the public suffix list, which is a file');
      out.dim('this page will not carry — the receiver’s own verdict is in the DKIM');
      out.dim('and SPF columns above, and it is the one that counted.');
    }

    out.rule();
    out.heading('What this report cannot tell you');
    out.dim('It is one receiver, over one period, seeing the mail that reached it.');
    out.dim('It carries no message content, no subjects and no recipients — only');
    out.dim('counts, IPs and results. It cannot say whether a failing source is');
    out.dim('malicious; that judgement is yours, from the volume and from knowing');
    out.dim('your own senders. The forwarder call above is a heuristic on two');
    out.dim('fields, not a fact. And a source missing from this report is not');
    out.dim('absent from the internet — it just did not send to this receiver.');
    out.line('');
    out.dim('Nothing here was uploaded. The XML was parsed by DOMParser in this tab');
    out.dim('and the source IPs of everything sending as you went nowhere.');

    setCopy('');
    setStatus('parsed ' + recs.length + ' records, ' + total + ' messages', 'is-ok');
  }

