/* ==========================================================================
   scripts/glossary-backlinks.js — puts the glossary's links back the other way.
   --------------------------------------------------------------------------
   glossary-terms.js already points 113 terms at the lab that demonstrates
   them. This walks that same data backwards and gives each lab page a short
   "the words this tool uses" block linking to those terms, so the two halves
   of the site reference each other instead of only one way round.

   IT IS IDEMPOTENT AND RE-RUNNABLE, which is the whole point. README says
   labs/*.html are generated by a tool outside this repo, and that a hand edit
   to one must be re-applied after any regeneration. A hand edit across 50-odd
   pages would not survive that. A marked block does:

     <!-- glossary-backlinks:start -->  …the block…  <!-- glossary-backlinks:end -->

   Present -> the block is replaced. Absent -> it is inserted before </main>.
   So after the lab generator runs, `npm run glossary:backlinks` restores
   every one of them in a single command.

       node scripts/glossary-backlinks.js            write the blocks
       node scripts/glossary-backlinks.js --check    report drift, write nothing
       node scripts/glossary-backlinks.js --remove   take every block back out

   Labs with no terms pointing at them are left completely untouched — an
   empty vocabulary box is worse than none.
   ========================================================================== */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const LABS = path.join(ROOT, 'labs');
const terms = require('./glossary-terms.js');

const START = '      <!-- glossary-backlinks:start — generated by scripts/glossary-backlinks.js, do not hand-edit -->';
const START_FIND = '      <!-- glossary-backlinks:start';
const END = '      <!-- glossary-backlinks:end -->';

const esc = (s) =>
  String(s).replace(/&(?![a-z]+;|#\d+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const slug = (s) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '')
   .replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// lab slug -> the terms that name it, alphabetically.
const byLab = new Map();
for (const t of terms) {
  if (!t.lab) continue;
  if (!byLab.has(t.lab)) byLab.set(t.lab, []);
  byLab.get(t.lab).push(t.t);
}
for (const list of byLab.values()) {
  list.sort((a, b) => a.localeCompare(b, 'en', { sensitivity: 'base' }));
}

function block(termNames) {
  let out = START + '\n';
  out += '      <section class="section-card lab-glossary">\n';
  out += '        <div class="section-heading">\n';
  out += '          <p class="eyebrow">Vocabulary</p>\n';
  out += '          <h2>The words this tool uses</h2>\n';
  out += '          <p>Each one is defined in plain language in the glossary.</p>\n';
  out += '        </div>\n';
  out += '        <ul class="lab-glossary-terms">\n';
  for (const name of termNames) {
    out += '          <li><a href="/glossary#term-' + slug(name) + '">' + esc(name) + '</a></li>\n';
  }
  out += '        </ul>\n';
  out += '        <p class="lab-glossary-all"><a href="/glossary">Browse the full glossary &rarr;</a></p>\n';
  out += '      </section>\n';
  out += END;
  return out;
}

function apply(src, next) {
  const a = src.indexOf(START_FIND);
  if (a >= 0) {
    const b = src.indexOf(END, a);
    if (b < 0) throw new Error('unterminated glossary-backlinks block');
    let after = b + END.length;
    // Insertion writes the block plus one newline. Removal has to take that
    // newline back, or every remove/apply cycle leaves another blank line
    // behind and the file drifts a line at a time.
    if (next === null && src[after] === '\n') after += 1;
    return src.slice(0, a) + (next === null ? '' : next) + src.slice(after);
  }
  if (next === null) return src;
  const m = src.lastIndexOf('    </main>');
  if (m < 0) return null;
  return src.slice(0, m) + next + '\n' + src.slice(m);
}

function main() {
  const check = process.argv.includes('--check');
  const remove = process.argv.includes('--remove');
  console.log('glossary backlinks');

  let written = 0;
  let drifted = 0;
  let noMain = [];
  let missing = [];

  for (const [lab, names] of [...byLab.entries()].sort()) {
    const file = path.join(LABS, lab + '.html');
    if (!fs.existsSync(file)) { missing.push(lab); continue; }
    const src = fs.readFileSync(file, 'utf8');
    const next = apply(src, remove ? null : block(names));
    if (next === null) { noMain.push(lab); continue; }
    if (next === src) continue;
    if (check) { drifted++; console.log('    drift  labs/' + lab + '.html'); continue; }
    fs.writeFileSync(file, next, 'utf8');
    written++;
  }

  // Any block sitting on a lab the term list no longer points at is stale and
  // has to come out, or a lab keeps a vocabulary box for terms that moved.
  for (const f of fs.readdirSync(LABS)) {
    if (!f.endsWith('.html')) continue;
    const lab = f.replace(/\.html$/, '');
    if (byLab.has(lab) && !remove) continue;
    const file = path.join(LABS, f);
    const src = fs.readFileSync(file, 'utf8');
    if (src.indexOf(START_FIND) < 0) continue;
    const next = apply(src, null);
    if (next === src) continue;
    if (check) { drifted++; console.log('    stale  labs/' + f); continue; }
    fs.writeFileSync(file, next, 'utf8');
    written++;
  }

  if (missing.length) {
    missing.forEach((l) => console.log('    - term list names /labs/' + l + ' but no such page exists'));
    console.error('  FAILED: ' + missing.length + ' unknown lab slug(s)');
    process.exit(1);
  }
  if (noMain.length) {
    noMain.forEach((l) => console.log('    - labs/' + l + '.html has no </main> to insert before'));
    console.error('  FAILED: ' + noMain.length + ' page(s) could not be edited');
    process.exit(1);
  }

  const linked = [...byLab.values()].reduce((n, l) => n + l.length, 0);
  console.log('  ' + byLab.size + ' labs carry ' + linked + ' term links');
  if (check && drifted) {
    console.error('  DRIFT: ' + drifted + ' page(s) — run `npm run glossary:backlinks`');
    process.exit(1);
  }
  console.log(check ? '  all pages current' : '  updated ' + written + ' page(s)');
}

main();
